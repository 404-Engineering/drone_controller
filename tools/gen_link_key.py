#!/usr/bin/env python3
"""Generate include/link_key.h with a random 128-bit link key.

The same file must be copied to the drone's radio firmware. Refuses to
overwrite an existing key unless --force is given, since replacing the key
unpairs the controller from the drone.
"""

import argparse
import os
import secrets
import sys

KEY_PATH = os.path.join(os.path.dirname(__file__), "..", "include", "link_key.h")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="overwrite an existing key")
    args = parser.parse_args()

    path = os.path.normpath(KEY_PATH)
    if os.path.exists(path) and not args.force:
        print(f"{path} already exists; use --force to replace it", file=sys.stderr)
        return 1

    key = secrets.token_bytes(16)
    rows = [", ".join(f"0x{b:02x}" for b in key[i:i + 8]) for i in (0, 8)]
    with open(path, "w") as f:
        f.write(
            "#pragma once\n\n"
            "// Link key shared by the controller and the drone. Generated by\n"
            "// tools/gen_link_key.py. Keep it secret: don't commit or share it.\n\n"
            "#include <stdint.h>\n\n"
            "static const uint8_t LINK_KEY[16] = {\n"
            f"    {rows[0]},\n"
            f"    {rows[1]},\n"
            "};\n"
        )
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
